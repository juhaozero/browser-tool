/**
 * 旧工具 ID → 新路径（含可选 query），用于书签与外链兼容
 * Navigate 目标形如 `hash?algo=md5` → `/tool/hash?algo=md5`
 */
export { toolRedirects, canonicalToolId } from '@/data/tool-redirects'

/** 根据路由参数查找工具定义，未找到时 ToolPage 会重定向首页 */
export function getToolById(id: string): ToolDefinition | undefined {
  return tools.find((t) => t.id === id)
}

export function getCategoryLabel(id: ToolDefinition['category']): string {
  return categories.find((c) => c.id === id)?.label ?? id
}
